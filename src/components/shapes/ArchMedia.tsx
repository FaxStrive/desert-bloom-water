// ArchMedia
//
// A media crop with a rounded or pointed top, sitting beside a text column.
// This is the "arches" family primitive: elegant-premium and
// corporate-professional lean on it because a doorway-shaped photograph
// reads as considered in a way a rectangle never does, and it costs nothing
// but a clip-path.
//
// The trap, and why this never touches Figure's own radius: Figure (and the
// `.figure` class it renders) already owns --radius-media, --figure-inset
// and overflow:hidden as a style-driven contract - see the long comment at
// the top of Figure.tsx. Setting border-radius or clip-path INSIDE Figure's
// own wrapper would fight that contract and silently break whichever
// treatment the active style declared. So this component never passes a
// shape onto Figure at all. Instead it wraps Figure in an outer div that
// this component owns, gives THAT div its own overflow:hidden and its own
// shape, and lets Figure keep rendering exactly as it always does one layer
// in. The visible result is an arch; the underlying image treatment is
// still whatever the style says it should be.
//
// Round vs pointed, and why round is a border-radius, not a clip-path: a
// clip-path polygon can only approximate a curve with straight segments, so
// a round arch made that way always shows a faint facet at 1440px even with
// forty points. Border-radius asks the browser to draw the actual curve, so
// "round" sets border-top-left-radius/border-top-right-radius to a clamped
// value instead. "pointed" has no equivalent curve-drawing property, so it
// is a clip-path polygon: forty-odd points along two mirrored power-curves
// meeting at a single point at top-center, dense enough near the peak that
// the point reads as sharp rather than chamfered. Both variants clip the
// top edge only; the sides stay vertical and the bottom stays flat, which
// is what keeps this a "doorway" rather than a lens.
//
// Reduced motion: nothing here moves. The shape is a layout fact like the
// bleed in BleedFigure, not a transition, so there is nothing to gate.

import { CTA_ACTION } from "@/lib/industry";
import Figure from "../sections/Figure";
import type { ReactNode } from "react";

export interface ArchMediaProps {
  imageSrc: string;
  imageAlt: string;
  variant?: "round" | "pointed";
  side?: "left" | "right";
  eyebrow?: string;
  /* A HEADLINE IS A NODE, NOT A STRING.
     Every reference page this pipeline is graded against closes its headings
     on an italic clause set in the accent - "Every faucet.", "For life." -
     and globals.css carries the h1/h2/h3 `em` rule that draws it. A `string`
     prop cannot hold that clause, so a build either shipped flat headlines or
     reached for dangerouslySetInnerHTML. ReactNode costs nothing: a caller
     passing a plain string is unaffected, and a caller with a clause writes
     the <em> itself. */
  headline?: ReactNode;
  body?: string;
  ctaLabel?: string;
  ctaHref?: string;
  tone?: "light" | "alt";
  /* An arch that opens a route (inside the first screen) is the page's lead
     picture. It must not be lazy-loaded behind a fade: assert-no-flat-scrim
     HERO-SATURATION measures the first in-viewport media at load and reads a
     not-yet-painted image as blank. Pass `priority` on that one and only that one. */
  priority?: boolean;
}

// Forty-one points, x in 0-100 across the top edge, y in 0-100 down the box,
// generated by two mirrored curves (y = 100 - 100 * (1 - |1 - x/50|)^1.7)
// that meet at (50, 0). The exponent above 1 keeps the shoulders of the
// arch rounder than a plain triangle while still closing to an honest point
// at the top rather than a flat chamfer. Bottom two points close the box.
const POINTED_ARCH_TOP: [number, number][] = Array.from({ length: 41 }, (_, i) => {
  const x = (i / 40) * 100;
  const t = Math.abs(1 - x / 50);
  const y = 100 - 100 * Math.pow(1 - t, 1.7);
  return [x, Math.min(100, Math.max(0, y))];
});
const POINTED_ARCH_CLIP = `polygon(${POINTED_ARCH_TOP.map(([x, y]) => `${x.toFixed(2)}% ${y.toFixed(2)}%`).join(", ")}, 100% 100%, 0% 100%)`;

export default function ArchMedia({
  imageSrc,
  imageAlt,
  variant = "round",
  side = "left",
  eyebrow,
  headline,
  body,
  ctaLabel,
  ctaHref,
  tone = "light",
  priority = false,
}: ArchMediaProps) {
  if (!headline) {
    return null;
  }

  const toneClass = tone === "alt" ? " on-alt" : "";
  const mediaIsRight = side === "right";

  return (
    <section className={`section${toneClass} overflow-hidden`} data-shape="arch-media">
      <div className="shell grid grid-cols-1 items-center gap-10 lg:grid-cols-2 lg:gap-16">
        <div
          className={mediaIsRight ? "order-1 lg:order-2" : "order-1 lg:order-1"}
          style={{
            overflow: "hidden",
            borderTopLeftRadius: variant === "round" ? "clamp(72px, 24vw, 220px)" : 0,
            borderTopRightRadius: variant === "round" ? "clamp(72px, 24vw, 220px)" : 0,
            clipPath: variant === "pointed" ? POINTED_ARCH_CLIP : undefined,
          }}
        >
          <Figure src={imageSrc} alt={imageAlt} fill sizes="(max-width: 1024px) 100vw, 50vw" wrapperClassName="relative aspect-[4/3] w-full" aspect="4/3" priority={priority} />
        </div>
        <div className={mediaIsRight ? "order-2 lg:order-1" : "order-2 lg:order-2"}>
          {eyebrow ? <span className="eyebrow mb-4 block">{eyebrow}</span> : null}
          <h2>{headline}</h2>
          {body ? <p className="lede mt-4">{body}</p> : null}
          {ctaLabel && ctaHref ? (
            <div className="mt-8">
              <a href={ctaHref} className="btn btn-primary btn-sweep" data-cta={CTA_ACTION}>
                <span>{ctaLabel}</span>
                <span className="btn-arrow" aria-hidden="true">
                  <svg width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round" className="block"><path d="M2 8h11" /><path d="M9 4l4 4-4 4" /></svg>
                </span>
              </a>
            </div>
          ) : null}
        </div>
      </div>
    </section>
  );
}
